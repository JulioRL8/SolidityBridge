import Foundation

@_spi(Tooling) public enum SwiftBindingGenerator {
    public static func generate(abi: ContractABI, named name: String) throws -> String {
        guard identifier(name) == name, name.first?.isUppercase == true else {
            throw SolidityBridgeError.invalidABI("Expected a Swift type name beginning with a capital letter")
        }
        var generator = Generator(reserved: [name, "contract", "Decode"])
        return try generator.source(abi, name: name)
    }

    private struct Field {
        let name: String
        let type: ValueType
    }

    private indirect enum ValueType {
        case scalar(swift: String, abiCase: String)
        case list(ValueType)
        case record(String)
        case topicHash

        var swift: String {
            switch self {
            case .scalar(let swift, _): swift
            case .list(let item): "[\(item.swift)]"
            case .record(let name): name
            case .topicHash: "Hash32"
            }
        }

        func encode(_ variable: String) -> String {
            switch self {
            case .scalar(_, let abiCase): ".\(abiCase)(\(variable))"
            case .list(let item): ".array(\(variable).map { item in \(item.encode("item")) })"
            case .record: "\(variable).abiValue"
            case .topicHash: preconditionFailure("Indexed hashes are decoded directly from event topics")
            }
        }

        func decode(_ value: String) -> String {
            switch self {
            case .scalar(_, let abiCase):
                "try Decode.\(abiCase)(\(value))"
            case .list(let item):
                "try Decode.array(\(value)) { item in \(item.decode("item")) }"
            case .record(let name):
                "try \(name)(abiValue: \(value))"
            case .topicHash:
                preconditionFailure("Indexed hashes are decoded directly from event topics")
            }
        }
    }

    private struct Generator {
        var reserved: Set<String>
        var declarations: [String] = []

        mutating func source(_ abi: ContractABI, name: String) throws -> String {
            var members: [String] = []
            var seenErrors: Set<String> = []
            let overloaded = Dictionary(grouping: abi.functions, by: \.name).filter { $0.value.count > 1 }
            for entry in abi.entries {
                guard ["function", "event", "error"].contains(entry.type),
                      let original = entry.name, let inputs = entry.inputs else { continue }
                let signature = try abiSignature(name: original, inputs: inputs.map { try ABIType($0) })
                switch entry.type {
                case "function":
                    let function = try abi.function(signature)
                    let proposed = overloaded[original] == nil ? original : original + "_" + function.selector.map { String(format: "%02x", $0) }.joined()
                    let method = claim(proposed)
                    members += try functionMembers(method, function: function, inputs: inputs, outputs: entry.outputs ?? [])
                case "event":
                    members += try eventMembers(original, event: abi.event(signature), inputs: inputs)
                case "error" where seenErrors.insert(signature).inserted:
                    try errorDeclaration(original, signature: signature, inputs: inputs)
                default:
                    continue
                }
            }
            let body = (declarations + members + [decoders()]).map { block in
                block.split(separator: "\n", omittingEmptySubsequences: false).map { $0.isEmpty ? "" : "    " + $0 }.joined(separator: "\n")
            }.joined(separator: "\n\n")
            return """
            // Generated by soliditybridge-bindings.
            import Foundation
            import SolidityBridge

            public struct \(name): Sendable {
                public let contract: EthereumContract

                public init(contract: EthereumContract) {
                    self.contract = contract
                }

            \(body)
            }

            """
        }

        mutating func functionMembers(
            _ method: String, function: ABIFunction, inputs: [ABIParameter], outputs: [ABIParameter]
        ) throws -> [String] {
            let arguments = try fields(inputs, stem: method + "Input", avoiding: ["from", "at", "value", "options", "signer", "wallet"])
            let returns = try fields(outputs, stem: method + "Output")
            let returnType: String
            switch returns.count {
            case 0: returnType = "Void"
            case 1: returnType = returns[0].type.swift
            default:
                returnType = claim(typeName(method) + "Result")
                declarations.append(record(returnType, fields: returns, extra: ""))
            }
            let signature = String(reflecting: function.signature)
            let params = arguments.enumerated().map { "\($0.element.name) p\($0.offset): \($0.element.type.swift)" }
            let values = arguments.enumerated().map { $0.element.type.encode("p\($0.offset)") }.joined(separator: ", ")
            let invocation = "\(signature), arguments: [\(values)]"
            let readOnly = function.mutability == .view || function.mutability == .pure
            let readMethod = readOnly ? method : claim("simulate" + typeName(method))
            var readParams = params + ["from: EthereumAddress? = nil"]
            if !readOnly { readParams.append("value: UInt256 = UInt256(0)") }
            readParams.append("at block: BlockTag = .latest")
            let call = readOnly ? "read" : "simulate"
            let value = readOnly ? "" : ", value: value"
            let callCode = "try await contract.\(call)(\(invocation), from: from\(value), at: block)"
            var body = "_ = \(callCode)"
            if !returns.isEmpty {
                let expression = returns.count == 1
                    ? returns[0].type.decode("values[0]")
                    : construct(returnType, fields: returns, values: "values")
                body = """
                let values = \(callCode)
                    guard values.count == \(returns.count) else { throw SolidityBridgeError.malformedABIData }
                    return \(expression)
                """
            }
            var methods = ["""
            public func \(readMethod)(\(readParams.joined(separator: ", "))) async throws -> \(returnType) {
                \(body)
            }
            """]
            if !readOnly {
                for (label, type) in [("signer", "any EthereumSigner"), ("wallet", "ExternalWallet")] {
                    let sendParams = params + ["\(label): \(type)", "options: TransactionOptions = .init()"]
                    methods.append("""
                    public func \(method)(\(sendParams.joined(separator: ", "))) async throws -> TransactionHash {
                        try await contract.send(\(invocation), \(label): \(label), options: options)
                    }
                    """)
                }
            }
            return methods
        }

        mutating func eventMembers(_ original: String, event: ABIEvent, inputs: [ABIParameter]) throws -> [String] {
            let name = claim(typeName(original) + "Event")
            let values = try fields(inputs, stem: name, event: true)
            let signature = String(reflecting: event.signature)
            let arguments = values.enumerated().map { index, field in
                let accessor = "event.arguments[\(index)].value"
                if case .topicHash = field.type {
                    return "\(field.name): try Decode.indexedHash(\(accessor))"
                }
                return "\(field.name): \(field.type.decode("Decode.eventValue(\(accessor))"))"
            }.joined(separator: ", ")
            declarations.append(record(name, fields: values, extra: """

                public static func decode(_ event: ContractEvent) throws -> Self {
                    guard event.signature == \(signature), event.arguments.count == \(values.count) else {
                        throw SolidityBridgeError.unrelatedLog
                    }
                    return Self(\(arguments))
                }
            """))
            let decode = claim("decode" + name)
            var members = ["""
            public func \(decode)(_ log: EthereumLog) throws -> \(name) {
                try \(name).decode(contract.decodeLog(log, as: \(signature)))
            }
            """]
            if !event.anonymous {
                let logs = claim("logs" + name)
                members.append("""
                public func \(logs)(from first: BlockTag, to last: BlockTag = .latest, indexed: [EventTopicFilter] = []) async throws -> [\(name)] {
                    try await contract.logs(\(signature), from: first, to: last, indexed: indexed).map(\(name).decode)
                }
                """)
            }
            return members
        }

        mutating func errorDeclaration(_ original: String, signature: String, inputs: [ABIParameter]) throws {
            let name = claim(typeName(original) + "Error")
            let values = try fields(inputs, stem: name)
            let result = construct("Self", fields: values, values: "revert.arguments")
            declarations.append(record(name, fields: values, extra: """

                public static func decode(_ revert: ContractRevert) throws -> Self? {
                    guard revert.signature == \(String(reflecting: signature)) else { return nil }
                    guard revert.arguments.count == \(values.count) else { throw SolidityBridgeError.malformedABIData }
                    return \(result)
                }
            """))
        }

        mutating func fields(
            _ parameters: [ABIParameter], stem: String, avoiding: Set<String> = [], event: Bool = false
        ) throws -> [Field] {
            var names = avoiding.union(["abiValue", "decode"])
            return try parameters.enumerated().map { index, parameter in
                let label = parameter.name.flatMap { $0.isEmpty ? nil : $0 } ?? "arg\(index)"
                let name = unique(identifier(label), in: &names)
                let abi = try ABIType(parameter)
                let type: ValueType
                if event, parameter.indexed == true, abi.isHashedWhenIndexed {
                    type = .topicHash
                } else {
                    type = try valueType(abi, components: parameter.components ?? [], stem: stem + typeName(name))
                }
                return Field(name: name, type: type)
            }
        }

        mutating func valueType(_ type: ABIType, components: [ABIParameter], stem: String) throws -> ValueType {
            switch type {
            case .address: return .scalar(swift: "EthereumAddress", abiCase: "address")
            case .bool: return .scalar(swift: "Bool", abiCase: "bool")
            case .uint: return .scalar(swift: "UInt256", abiCase: "uint")
            case .int: return .scalar(swift: "Int256", abiCase: "int")
            case .bytes: return .scalar(swift: "Data", abiCase: "bytes")
            case .fixedBytes: return .scalar(swift: "Data", abiCase: "fixedBytes")
            case .string: return .scalar(swift: "String", abiCase: "string")
            case .array(let item, _): return .list(try valueType(item, components: components, stem: stem + "Item"))
            case .tuple:
                let name = claim(typeName(stem) + "Tuple")
                let values = try fields(components, stem: name)
                let expressions = values.map { $0.type.encode("self." + $0.name) }.joined(separator: ", ")
                declarations.append(record(name, fields: values, extra: """

                    fileprivate var abiValue: ABIValue { .tuple([\(expressions)]) }

                    fileprivate init(abiValue: ABIValue) throws {
                        guard case .tuple(let fields) = abiValue, fields.count == \(values.count) else {
                            throw SolidityBridgeError.malformedABIData
                        }
                        self = \(construct("Self", fields: values, values: "fields"))
                    }
                """))
                return .record(name)
            }
        }

        private func decoders() -> String {
            let scalars = [
                ("address", "EthereumAddress"), ("bool", "Bool"), ("uint", "UInt256"),
                ("int", "Int256"), ("bytes", "Data"), ("fixedBytes", "Data"), ("string", "String")
            ].map { abiCase, type in
                """
                    static func \(abiCase)(_ value: ABIValue) throws -> \(type) {
                        guard case .\(abiCase)(let decoded) = value else { throw SolidityBridgeError.malformedABIData }
                        return decoded
                    }
                """
            }.joined(separator: "\n\n")
            return """
            private enum Decode {
            \(scalars)

                static func array<T>(_ value: ABIValue, _ decode: (ABIValue) throws -> T) throws -> [T] {
                    guard case .array(let items) = value else { throw SolidityBridgeError.malformedABIData }
                    return try items.map(decode)
                }

                static func eventValue(_ value: ContractEvent.Argument.Value) throws -> ABIValue {
                    guard case .decoded(let decoded) = value else { throw SolidityBridgeError.malformedABIData }
                    return decoded
                }

                static func indexedHash(_ value: ContractEvent.Argument.Value) throws -> Hash32 {
                    guard case .indexedHash(let hash) = value else { throw SolidityBridgeError.malformedABIData }
                    return hash
                }
            }
            """
        }

        mutating func claim(_ name: String) -> String { unique(identifier(name), in: &reserved) }

        private func record(_ name: String, fields: [Field], extra: String) -> String {
            let properties = fields.map { "    public let \($0.name): \($0.type.swift)\n" }.joined()
            let params = fields.map { "\($0.name): \($0.type.swift)" }.joined(separator: ", ")
            let assignments = fields.map { "        self.\($0.name) = \($0.name)\n" }.joined()
            return "public struct \(name): Equatable, Sendable {\n\(properties)\n    public init(\(params)) {\n\(assignments)    }\n\(extra)\n}"
        }

        private func construct(_ name: String, fields: [Field], values: String) -> String {
            let arguments = fields.enumerated().map { "\($0.element.name): \($0.element.type.decode("\(values)[\($0.offset)]"))" }
            return "\(name)(\(arguments.joined(separator: ", ")))"
        }
    }

    private static func typeName(_ name: String) -> String { name.prefix(1).uppercased() + name.dropFirst() }

    private static func unique(_ name: String, in names: inout Set<String>) -> String {
        if names.insert(name).inserted { return name }
        var suffix = 2
        while !names.insert(name + "_" + String(suffix)).inserted { suffix += 1 }
        return name + "_" + String(suffix)
    }

    private static func identifier(_ name: String) -> String {
        let result = String(name.map { char in
            char.isASCII && (char.isLetter || char.isNumber || char == "_") ? char : "_"
        })
        if result.isEmpty || result == "_" { return "arg" }
        let reserved: Set<String> = [
            "associatedtype", "actor", "class", "deinit", "enum", "extension", "fileprivate", "func",
            "import", "init", "inout", "internal", "let", "open", "operator", "private", "protocol",
            "public", "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case",
            "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if",
            "in", "repeat", "return", "switch", "where", "while", "as", "Any", "false", "is", "nil",
            "self", "Self", "super", "throw", "throws", "true", "try", "Type", "Protocol", "await",
            "async", "some", "any", "borrowing", "consuming", "isolated", "nonisolated", "package",
            "copy", "consume", "each", "sending", "macro",
            "Foundation", "SolidityBridge", "EthereumContract", "EthereumLog", "EthereumAddress",
            "TransactionHash", "TransactionOptions", "EthereumSigner", "ExternalWallet", "ContractEvent",
            "ContractRevert", "SolidityBridgeError", "EventTopicFilter", "ABIValue", "Hash32", "BlockTag",
            "Equatable", "Sendable", "Data", "String", "Bool", "UInt256", "Int256", "Void", "Swift"
        ]
        return result.first?.isNumber == true || reserved.contains(result) ? "_" + result : result
    }
}

private extension ABIType {
    var isHashedWhenIndexed: Bool {
        switch self {
        case .array, .tuple, .string, .bytes: true
        default: false
        }
    }
}
